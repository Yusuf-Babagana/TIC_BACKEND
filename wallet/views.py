class WalletBalanceView(APIView):
    authentication_classes = [JWTAuthentication]
    permission_classes = [IsAuthenticated]

    def get(self, request):
        wallet = request.user.wallet
        return Response({
            "balance": str(wallet.balance),
            "bank_name": wallet.bank_name,
            "account_number": wallet.account_number,
        }, status=200)


class RawJsonPassthroughParser(BaseParser):
    media_type = "*/*"

    def parse(self, stream, media_type=None, parser_context=None):
        return stream.read()


@method_decorator(csrf_exempt, name="dispatch")
class MonnifyWebhookView(APIView):
    parser_classes = [RawJsonPassthroughParser]
    permission_classes = []
    authentication_classes = []

    def post(self, request):
        raw_body = request.data
        try:
            payload = json.loads(raw_body.decode("utf-8"))
            print(f"DEBUG: WEBHOOK RECEIVED: {payload}")

            event_data = payload.get("eventData", {})

            amount = Decimal(str(event_data.get("amountPaid", "0")))
            account_number = event_data.get("destinationAccountNumber")
            ref = event_data.get("destinationAccountReference") or event_data.get("paymentReference")
            txn_ref = event_data.get("transactionReference")

            print(f"DEBUG: amount={amount} account={account_number} ref={ref} txn_ref={txn_ref}")

            from wallet.models import Wallet, Transaction

            # Try to find the wallet by account_number first
            wallet = None
            if account_number:
                try:
                    wallet = Wallet.objects.get(account_number=account_number)
                    print(f"DEBUG: Found wallet by account_number: user={wallet.user_id}")
                except Wallet.DoesNotExist:
                    print(f"DEBUG: No wallet for account_number={account_number}")

            # Fallback: grab any wallet
            if wallet is None:
                wallet = Wallet.objects.first()
                print(f"DEBUG: Fallback to first wallet: user={wallet.user_id}")

            Transaction.objects.create(
                user=wallet.user,
                trans_type="DEPOSIT",
                amount=amount,
                status="FORCE_RECORDED_TEST",
                reference=txn_ref or f"FORCE-{account_number or 'unknown'}",
            )
            print("DEBUG: Force-recorded test transaction!")
            return Response({"status": "force_recorded"}, status=200)

        except Exception as e:
            print(f"DEBUG: FATAL ERROR: {str(e)}")
            return Response({"error": str(e)}, status=500)


class TransactionHistoryView(generics.ListAPIView):
    serializer_class = TransactionSerializer
    authentication_classes = [JWTAuthentication]
    permission_classes = [IsAuthenticated]

    def get_queryset(self):
        return Transaction.objects.filter(user=self.request.user).order_by(
            "-created_at"
        )


class GenerateAccountView(APIView):
    authentication_classes = [JWTAuthentication]
    permission_classes = [IsAuthenticated]

    def post(self, request):
        wallet = request.user.wallet
        if wallet.account_number:
            return Response(
                {"message": "Account already exists"}, status=status.HTTP_400_BAD_REQUEST
            )

        try:
            account = MonnifyService.create_reserved_account(request.user)
            wallet.bank_name = account["bank_name"]
            wallet.account_number = account["account_number"]
            wallet.account_reference = account["account_reference"]
            wallet.save()
            return Response(
                {"message": "Account generated successfully", "data": account},
                status=status.HTTP_200_OK,
            )
        except MonnifyError as e:
            return Response({"message": str(e)}, status=status.HTTP_400_BAD_REQUEST)
        except Exception as e:
            logger.error("GenerateAccount Crash: %s", str(e))
            logger.error(traceback.format_exc())
            return Response(
                {
                    "status": "error",
                    "message": "Failed to connect to identity provider",
                    "details": str(e),
                },
                status=status.HTTP_502_BAD_GATEWAY,
            )


class SubmitBVNView(APIView):
    authentication_classes = [JWTAuthentication]
    permission_classes = [IsAuthenticated]

    def post(self, request):
        logger.info(
            "SubmitBVNView hit by user id=%s username=%s email=%s",
            request.user.id,
            request.user.username,
            request.user.email,
        )

        bvn = request.data.get("bvn")
        nin = request.data.get("nin")

        if settings.DEBUG:
            if not bvn or bvn in ["", "string", "00000000000"]:
                bvn = "22241354089"
            if not nin or nin in ["", "string"]:
                nin = "72533591954"

        bvn = (bvn or "").strip()
        nin = (nin or "").strip()

        if not re.fullmatch(r"\d{11}", bvn):
            return Response(
                {"error": "BVN must be exactly 11 digits"},
                status=status.HTTP_400_BAD_REQUEST,
            )

        wallet = request.user.wallet

        try:
            account = MonnifyService.create_reserved_account(
                request.user, bvn=bvn
            )
            wallet.bank_name = account["bank_name"]
            wallet.account_number = account["account_number"]
            wallet.account_reference = account["account_reference"]
            wallet.save(update_fields=["bank_name", "account_number", "account_reference"])

            response_data = {
                "bank_name": account["bank_name"],
                "account_number": account["account_number"],
                "account_reference": account["account_reference"],
            }

            return Response(
                {
                    "message": "Account generated successfully",
                    "data": response_data,
                },
                status=status.HTTP_200_OK,
            )

        except MonnifyError as e:
            return Response(
                {"error": str(e)}, status=status.HTTP_400_BAD_REQUEST
            )
        except Exception as e:
            logger.error("BVN Submission Crash: %s", str(e))
            logger.error(traceback.format_exc())
            return Response(
                {
                    "status": "error",
                    "message": "Failed to connect to identity provider",
                    "details": str(e),
                },
                status=status.HTTP_502_BAD_GATEWAY,
            )
